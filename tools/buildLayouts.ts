// Builds src/explorer/db2Layouts.generated.ts from WoWDBDefs (https://github.com/wowdev/WoWDBDefs):
// for each table that src/explorer/fields.ts lists fields of, and for every layout hash the
// definitions know of it, where each listed field is in that layout. The fields are numbered by
// their place in the list, so the code doesn't depend on any game version's layout.
// Definitions are downloaded to .cache/wowdbdefs/ once.
// Usage: bun run layouts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { DB2_FILES } from '../src/explorer/db2Files';
import { FIELD_SOURCES } from '../src/explorer/fields';

/** The version whose newest layout is read for a layout hash not known here (Forever's). */
const FALLBACK_VERSION = '1.60.';
const CACHE = '.cache/wowdbdefs';
const OUT = 'src/explorer/db2Layouts.generated.ts';
const url = (table: string) => `https://raw.githubusercontent.com/wowdev/WoWDBDefs/master/definitions/${table}.dbd`;

export interface Layout {
	/** The fields stored in each record. */
	fields: string[];
	builds: string[];
}

/** Every layout of a table, by layout hash. */
export function parseLayouts(dbd: string): Map<string, Layout> {
	const layouts = new Map<string, Layout>();
	for (const block of dbd.split(/\r?\n\r?\n/)) {
		const lines = block.split(/\r?\n/).filter((l) => l.trim());
		const hashes = lines.filter((l) => l.startsWith('LAYOUT ')).flatMap((l) => l.slice(7).split(',').map((h) => h.trim().toUpperCase()));
		if (!hashes.length) continue;
		const builds = lines.filter((l) => l.startsWith('BUILD ')).flatMap((l) => l.slice(6).split(',').map((b) => b.trim()));
		const fields: string[] = [];
		for (const line of lines) {
			if (/^(LAYOUT|BUILD|COMMENT) /.test(line)) continue;
			const [, annotations = '', name] = line.match(/^(?:\$([^$]*)\$)?([^<[\s]+)/) ?? [];
			// An ID or relation kept apart from the records is not one of their fields.
			if (annotations.split(',').includes('noninline')) continue;
			fields.push(name);
		}
		for (const hash of hashes) if (!layouts.has(hash)) layouts.set(hash, { fields, builds });
	}
	return layouts;
}

const buildNumber = (build: string) => Number(build.split('.').pop());

/** The layout of the newest build of a version (such as '1.60.'), or null if the table has none. */
export function newestLayout(layouts: Map<string, Layout>, version: string): { hash: string; layout: Layout } | null {
	let best: { hash: string; layout: Layout; build: number } | null = null;
	for (const [hash, layout] of layouts) {
		for (const b of layout.builds) {
			if (b.startsWith(version) && (!best || buildNumber(b) > best.build)) best = { hash, layout, build: buildNumber(b) };
		}
	}
	return best;
}

/** Where each wanted field is in a layout, null where it has none. */
export function fieldMapOf(wanted: string[], layout: string[]): (number | null)[] {
	return wanted.map((name) => {
		const i = layout.indexOf(name);
		return i < 0 ? null : i;
	});
}

const list = (map: (number | null)[]) => `[${map.map((v) => v ?? 'null').join(', ')}]`;

async function main(): Promise<void> {
	mkdirSync(CACHE, { recursive: true });
	let tables = '';
	for (const [table, wanted] of Object.entries(FIELD_SOURCES)) {
		const fdid = DB2_FILES[table as keyof typeof DB2_FILES];
		if (fdid === undefined) throw new Error(`${table} is not in DB2_FILES`);
		const file = `${CACHE}/${table}.dbd`;
		if (!existsSync(file)) {
			console.log('Downloading', url(table));
			const res = await fetch(url(table));
			if (!res.ok) throw new Error(`${table}.dbd: HTTP ${res.status}`);
			writeFileSync(file, await res.text());
		}
		const all = parseLayouts(readFileSync(file, 'utf8'));
		const fallback = newestLayout(all, FALLBACK_VERSION);
		if (!fallback) throw new Error(`${table}: no layout of version ${FALLBACK_VERSION}`);
		const fallbackMap = fieldMapOf(wanted, fallback.layout.fields);
		const missing = wanted.filter((_, i) => fallbackMap[i] === null);
		if (missing.length) throw new Error(`${table} has no ${missing.join(', ')} in its layout of version ${FALLBACK_VERSION}`);
		let rows = '';
		for (const [hash, layout] of all) rows += `\t\t\t0x${hash.toLowerCase()}: ${list(fieldMapOf(wanted, layout.fields))},\n`;
		tables += `\t// ${table}\n\t${fdid}: {\n\t\tfallback: ${list(fallbackMap)},\n\t\tlayouts: {\n${rows}\t\t},\n\t},\n`;
	}
	writeFileSync(OUT, `// Generated by tools/buildLayouts.ts from WoWDBDefs; do not edit.

/**
 * By table file ID: where each field of the table's list in fields.ts is in the layout of each
 * layout hash (null where that layout hasn't it), and in the layout read for a hash not listed
 * (the newest of version ${FALLBACK_VERSION}).
 */
export const GENERATED_LAYOUTS: Record<number, { fallback: (number | null)[]; layouts: Record<number, (number | null)[]> }> = {
${tables}};
`);
	console.log('Wrote', OUT);
}

if (import.meta.main) await main();

// Builds src/explorer/db2Layouts.generated.ts from WoWDBDefs (https://github.com/wowdev/WoWDBDefs):
// per table, the name of each field as the code numbers them (the reference layout, Forever's) and,
// for every other layout hash the definitions know, where each of those fields is in it.
// Definitions are downloaded to .cache/wowdbdefs/ once.
// Usage: bun run layouts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { DB2_FILES } from '../src/explorer/db2Files';

/** Version whose layouts the code numbers fields by (Forever); its newest build's layout is the reference. */
const REFERENCE_VERSION = '1.60.';
const CACHE = '.cache/wowdbdefs';
const OUT = 'src/explorer/db2Layouts.generated.ts';
const url = (table: string) => `https://raw.githubusercontent.com/wowdev/WoWDBDefs/master/definitions/${table}.dbd`;

export interface Layout {
	/** The fields stored in each record. */
	fields: string[];
	builds: string[];
}

/** Every layout of a table, by layout hash. */
export function parseLayouts(dbd: string): Map<string, Layout> {
	const layouts = new Map<string, Layout>();
	for (const block of dbd.split(/\r?\n\r?\n/)) {
		const lines = block.split(/\r?\n/).filter((l) => l.trim());
		const hashes = lines.filter((l) => l.startsWith('LAYOUT ')).flatMap((l) => l.slice(7).split(',').map((h) => h.trim().toUpperCase()));
		if (!hashes.length) continue;
		const builds = lines.filter((l) => l.startsWith('BUILD ')).flatMap((l) => l.slice(6).split(',').map((b) => b.trim()));
		const fields: string[] = [];
		for (const line of lines) {
			if (/^(LAYOUT|BUILD|COMMENT) /.test(line)) continue;
			const [, annotations = '', name] = line.match(/^(?:\$([^$]*)\$)?([^<[\s]+)/) ?? [];
			// An ID or relation kept apart from the records is not one of their fields.
			if (annotations.split(',').includes('noninline')) continue;
			fields.push(name);
		}
		for (const hash of hashes) if (!layouts.has(hash)) layouts.set(hash, { fields, builds });
	}
	return layouts;
}

const buildNumber = (build: string) => Number(build.split('.').pop());

/** The layout of the newest build of the reference version, or null if the table has none. */
export function referenceLayout(layouts: Map<string, Layout>): { hash: string; layout: Layout } | null {
	let best: { hash: string; layout: Layout; build: number } | null = null;
	for (const [hash, layout] of layouts) {
		for (const b of layout.builds) {
			if (b.startsWith(REFERENCE_VERSION) && (!best || buildNumber(b) > best.build)) best = { hash, layout, build: buildNumber(b) };
		}
	}
	return best;
}

/** Where each reference field is in a layout (null where it has none), or null if they are the same. */
export function fieldMapOf(reference: string[], layout: string[]): (number | null)[] | null {
	const map = reference.map((name) => {
		const i = layout.indexOf(name);
		return i < 0 ? null : i;
	});
	return map.every((v, i) => v === i) && layout.length === reference.length ? null : map;
}

async function main(): Promise<void> {
	mkdirSync(CACHE, { recursive: true });
	let fields = '';
	let layouts = '';
	for (const [table, fdid] of Object.entries(DB2_FILES)) {
		const file = `${CACHE}/${table}.dbd`;
		if (!existsSync(file)) {
			console.log('Downloading', url(table));
			const res = await fetch(url(table));
			if (!res.ok) throw new Error(`${table}.dbd: HTTP ${res.status}`);
			writeFileSync(file, await res.text());
		}
		const all = parseLayouts(readFileSync(file, 'utf8'));
		const reference = referenceLayout(all);
		if (!reference) throw new Error(`${table}: no layout of version ${REFERENCE_VERSION}`);
		const names = reference.layout.fields;
		fields += `\t${table}: {\n${names.map((name, i) => `\t\t${name}: ${i},\n`).join('')}\t},\n`;
		let rows = '';
		for (const [hash, layout] of all) {
			const map = fieldMapOf(names, layout.fields);
			rows += `\t\t0x${hash.toLowerCase()}: ${map ? `[${map.map((v) => v ?? 'null').join(', ')}]` : 'null'},\n`;
		}
		layouts += `\t// ${table}\n\t${fdid}: {\n${rows}\t},\n`;
	}
	writeFileSync(OUT, `// Generated by tools/buildLayouts.ts from WoWDBDefs; do not edit.
// Field numbers of the reference layout (Forever's), by table and field name.
export const FIELDS = {
${fields}} as const;

/** By table file ID, then layout hash: where each reference field is in that layout, null where it has none; null for a layout the same as the reference. */
export const GENERATED_LAYOUTS: Record<number, Record<number, (number | null)[] | null>> = {
${layouts}};
`);
	console.log('Wrote', OUT);
}

if (import.meta.main) await main();
